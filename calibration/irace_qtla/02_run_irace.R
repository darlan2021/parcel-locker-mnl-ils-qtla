rm(list = ls())
suppressPackageStartupMessages(library(irace))
if (!file.exists("preflight_ok.txt")) stop('Run source("01_preflight.R") first.')
if (file.exists("irace_qtla_calibration.Rdata")) stop("Old irace log exists. Move/delete it first.")
if (file.exists("run_level_results.csv")) stop("Old run_level_results.csv exists. Move/delete it first.")
scenario <- readScenario(filename="scenario.txt")
checkIraceScenario(scenario)
cat("============================================================\n")
cat("QT-LA OFFICIAL IRACE CALIBRATION\n")
cat("============================================================\n")
cat("Components ON: trust_region + neighbor_oa + local_polish + no_good\n")
cat("Overall QT-LA time limit per run: 3600 s\n\n")
start_time <- Sys.time()
irace_results <- irace(scenario=scenario)
end_time <- Sys.time()
wall <- as.numeric(difftime(end_time,start_time,units="secs"))
saveRDS(irace_results,"irace_qtla_results.rds")
cat("\nFINAL ELITES\n")
print(getFinalElites(irace_results,n=0))
capture.output(summary(irace_results),file="irace_summary.txt")
writeLines(c(paste("Start:",format(start_time,"%Y-%m-%d %H:%M:%S %z")),paste("End:",format(end_time,"%Y-%m-%d %H:%M:%S %z")),paste("Wall_clock_seconds:",sprintf("%.2f",wall)),paste("irace_version:",as.character(packageVersion("irace"))),paste("R_version:",R.version.string),paste("irace_seed:",scenario$seed),paste("maxExperiments:",scenario$maxExperiments),paste("blockSize:",scenario$blockSize),"design_instances: 72","design_blocks: 18 x 4","N_groups: 60,100,200,400","p_low: 3,5,10,20","p_high: 6,10,20,30","alpha: 0.5,1.0,2.0","instance_seeds: 11,12,13","components_fixed_ON: trust_region,neighbor_oa,local_polish,no_good","overall_time_limit_seconds: 3600"),"calibration_metadata.txt")
cat("\nOFFICIAL QT-LA CALIBRATION FINISHED\n")
