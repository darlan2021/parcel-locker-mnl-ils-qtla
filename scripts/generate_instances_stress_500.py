import sys
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from data import CData


# ------------------------------------------------------------
# OFFICIAL STRESS-TEST INSTANCE SEEDS
# ------------------------------------------------------------
INSTANCE_SEEDS = [21, 22, 23]

EXPERIMENTS = {
    500: [20, 25, 30],
}

LAMBDA_VALUES = [0.5, 1.0, 2.0]

# Stress-test instances: N = 500.
OUTPUT_DIR = (
    ROOT
    / "instances"
    / "instances_seed_21_22_23_N_500"
)


def save_instance(dt: CData, output_dir: Path) -> None:
    """
    Save only fields actually generated by the current CData constructor.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    npz_path = output_dir / f"{dt.name}.npz"
    json_path = output_dir / f"{dt.name}.json"

    np.savez_compressed(
        npz_path,
        n_i=dt.n_i,
        n_j=dt.n_j,
        n_k=dt.n_k,
        p=dt.p,
        alpha=dt.alpha,
        seed=dt.seed,
        customer_xy=dt.customer_xy,
        existing_xy=dt.existing_xy,
        candidate_xy=dt.candidate_xy,
        demand=dt.demand,
        distance_existing=dt.distance_existing,
        distance_candidate=dt.distance_candidate,
        service_existing=dt.service_existing,
        service_candidate=dt.service_candidate,
        log_b_existing=dt.log_b_existing,
        log_b_candidate=dt.log_b_candidate,
        b_existing=dt.b_existing,
        b_candidate=dt.b_candidate,
        a_existing=dt.a_existing,
        a_candidate=dt.a_candidate,
        a=dt.a,
        b=dt.b,
        U=dt.U,
        U_sum=dt.U_sum,
    )

    metadata = dict(dt.metadata)
    metadata.update(
        {
            "instance_name": dt.name,
            "npz_file": npz_path.name,
            "n_total_facilities": dt.n,
            "total_nodes_style_N": 2 * dt.n_i,
        }
    )

    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(metadata, fh, indent=2)

    print(
        f"[OK] {dt.name:<30s} "
        f"I={dt.n_i:3d} K={dt.n_k:3d} J={dt.n_j:3d} "
        f"p={dt.p:2d} lambda={dt.lambda_:3.1f} "
        f"seed={dt.seed}"
    )


def main():
    print("=" * 78)
    print("GENERATING STRESS-TEST INSTANCES - N=500")
    print("=" * 78)
    print(f"Output directory : {OUTPUT_DIR.resolve()}")
    print(f"Instance seeds    : {INSTANCE_SEEDS}")
    print()

    count = 0

    for instance_seed in INSTANCE_SEEDS:
        for N, p_values in EXPERIMENTS.items():
            for p in p_values:
                for lambda_ in LAMBDA_VALUES:

                    dt = CData.from_total_nodes(
                        N=N,
                        p=p,
                        lambda_=lambda_,
                        seed=instance_seed,
                    )

                    save_instance(dt, OUTPUT_DIR)
                    count += 1

    print()
    print("=" * 78)
    print(f"Finished. {count} stress-test instances generated.")
    print("=" * 78)

    expected = (
        len(INSTANCE_SEEDS)
        * sum(len(p_values) for p_values in EXPERIMENTS.values())
        * len(LAMBDA_VALUES)
    )

    print(f"Expected : {expected}")
    print(f"Generated: {count}")

    if count != expected:
        raise RuntimeError(
            f"Unexpected number of stress-test instances: "
            f"{count}. Expected {expected}."
        )

    print("Stress-test set N=500 successfully generated.")


if __name__ == "__main__":
    main()